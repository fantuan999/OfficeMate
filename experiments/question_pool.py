"""
企业内部问答问题池，用于 Phase 3 workload 实验。

设计原则：
- 每个"话题组"包含 2-3 个语义相近的问题，用于测试 cache semantic hit
- 话题组之间差异较大，用于测试 cache miss
- 共 10 个话题组，约 30 个问题
"""

# ── 话题组（语义相近，易触发 cache HIT）─────────────────────────
QUESTION_GROUPS = {
    "年假": [
        "年假怎么申请？",
        "年假如何申请？",
        "年假申请流程是什么？",
    ],
    "报销": [
        "报销差旅费需要哪些材料？",
        "差旅报销需要提交什么？",
        "出差报销需要哪些单据？",
    ],
    "vpn": [
        "VPN连接失败怎么处理？",
        "VPN连不上怎么办？",
        "VPN无法连接如何解决？",
    ],
    "密码重置": [
        "邮箱密码忘了怎么办？",
        "办公系统密码如何重置？",
        "账号密码锁定了怎么解锁？",
    ],
    "采购": [
        "采购设备需要走什么流程？",
        "购买办公设备如何申请？",
        "采购审批流程是什么？",
    ],
    "请假": [
        "病假需要提供什么证明？",
        "请病假需要什么材料？",
        "请假需要提前多久申请？",
    ],
    "入职": [
        "新员工入职需要准备什么材料？",
        "入职第一天需要做什么？",
        "员工入职流程是什么？",
    ],
    "绩效": [
        "绩效考核是怎么进行的？",
        "绩效评分标准是什么？",
        "绩效考核周期是多久？",
    ],
    "打印机": [
        "打印机连接失败怎么处理？",
        "打印机无法使用如何解决？",
        "如何连接办公室打印机？",
    ],
    "出差": [
        "出差申请需要提前多久提交？",
        "出差审批流程是什么？",
        "如何申请出差？",
    ],
}

# ── 扁平化问题列表（实验用）────────────────────────────────────
QUESTIONS = [q for group in QUESTION_GROUPS.values() for q in group]

# ── 按话题组的代表性问题（每组取第一个，用于低重复 workload）───
REPRESENTATIVE_QUESTIONS = [qs[0] for qs in QUESTION_GROUPS.values()]


if __name__ == "__main__":
    print(f"总问题数: {len(QUESTIONS)}")
    print(f"话题组数: {len(QUESTION_GROUPS)}")
    print(f"代表性问题: {len(REPRESENTATIVE_QUESTIONS)}")
    print()
    for topic, qs in QUESTION_GROUPS.items():
        print(f"【{topic}】")
        for q in qs:
            print(f"  - {q}")
